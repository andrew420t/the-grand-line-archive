const EN_CARDLIST = 'https://en.onepiece-cardgame.com/cardlist/?series=569205'
const JP_CARDLIST = 'https://www.onepiece-cardgame.com/cardlist/?series=550205'

function officialDirectImageUrl(imageId, language) {
  const host = language === 'jp' ? 'https://www.onepiece-cardgame.com' : 'https://en.onepiece-cardgame.com'
  return host + '/images/cardlist/card/' + encodeURIComponent(imageId) + '.png'
}

function makeSupplementalMatch(printing, language) {
  const imageId = language === 'jp' ? printing.imageIdJp : printing.imageIdEn
  const exactProxy = buildOfficialImageProxyUrl(imageId, language)
  const baseProxy = buildOfficialImageProxyUrl(printing.cardNumber, language)
  const exactDirect = officialDirectImageUrl(imageId, language)
  const baseDirect = officialDirectImageUrl(printing.cardNumber, language)
  const imageUrls = [...new Set([exactProxy, imageId !== printing.cardNumber ? baseProxy : '', exactDirect, baseDirect].filter(Boolean))]
  const isJapanese = language === 'jp'
  return {
    id: 'supplemental-eb05:' + language + ':' + imageId,
    cardKey: 'eb05:' + printing.cardNumber,
    printingKey: 'eb05:' + imageId,
    cardNumber: printing.cardNumber,
    name: isJapanese ? printing.japaneseName : printing.name,
    language: isJapanese ? 'Japanese' : 'English',
    languageCode: language,
    category: printing.category,
    colors: printing.color,
    cost: printing.cost,
    life: printing.life,
    power: printing.power,
    counter: printing.counter,
    attributes: printing.attribute,
    traits: printing.types,
    effect: printing.effect,
    trigger: printing.trigger,
    rarity: printing.rarity,
    variant: printing.variant,
    variantLabel: printing.variantLabel,
    imageUrl: exactProxy || exactDirect,
    imageUrls,
    fallbackImageUrl: imageId !== printing.cardNumber ? (baseProxy || baseDirect) : exactDirect,
    sourceText: 'Bandai official EB-05 card-list metadata and language-specific artwork identifiers, fetched 2026-11-27.',
    setCode: 'EB-05',
    setName: 'ONE PIECE Heroines Edition vol.2 [EB-05]',
    productKind: 'extra booster',
    sourceUrl: isJapanese ? JP_CARDLIST : EN_CARDLIST,
    blockIcon: printing.blockIcon,
    source: 'Bandai official ' + (isJapanese ? 'Japanese' : 'English') + ' EB-05 ' + printing.variantLabel + ' image via Cloudflare proxy',
    officialCardlistUrl: isJapanese ? JP_CARDLIST : EN_CARDLIST,
    supplementalOfficial: true,
    verificationStatus: 'pending-live-image-check',
  }
}

export function getEb05SupplementalMatches(cardNumber = '') {
  const normalized = String(cardNumber || '').toUpperCase().replace(/[^A-Z0-9]/g, '').replace(/^((?:OP|EB|ST|PRB)\d{2})(\d{3})$/, '$1-$2')
  return EB05_OFFICIAL_PRINTINGS
    .filter((printing) => !normalized || printing.cardNumber === normalized)
    .flatMap((printing) => ['en', 'jp'].map((language) => makeSupplementalMatch(printing, language)))
}

export function getEb05ImageTestItems(language = 'en') {
  return EB05_OFFICIAL_PRINTINGS.map((printing) => {
    const imageId = language === 'jp' ? printing.imageIdJp : printing.imageIdEn
    return {
      imageId,
      cardNumber: printing.cardNumber,
      imageUrl: buildOfficialImageProxyUrl(imageId, language) || officialDirectImageUrl(imageId, language),
    }
  })
}
